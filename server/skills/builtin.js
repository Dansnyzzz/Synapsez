export const BUILTIN_BY_ID = new Map(BUILTIN_SKILLS.map((skill) => [skill.id, skill]));

/** Matched loosely, so a model that types the name rather than the id still lands. */
export function findBuiltinSkill(name) {
  const wanted = String(name || '').trim().toLowerCase();
  if (!wanted) return null;
  return (
    BUILTIN_BY_ID.get(wanted) ||
    BUILTIN_SKILLS.find((skill) => skill.id.toLowerCase() === wanted) ||
    BUILTIN_SKILLS.find((skill) => skill.name.toLowerCase() === wanted) ||
    // "docx", "xlsx", "pdf" — what somebody would actually type.
    BUILTIN_SKILLS.find((skill) => skill.id.split(':')[1] === wanted) ||
    null
  );
}
